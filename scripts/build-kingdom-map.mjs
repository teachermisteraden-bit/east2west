/**
 * Derives the Saudi Arabia outline used by the "Across the Kingdom" scene.
 *
 * Source: Natural Earth (public domain), by way of the `world-atlas` package's
 * 50m countries topology. Run once and the small result is committed, so the
 * site never ships a megabyte of world geometry to draw one country.
 *
 *   node scripts/build-kingdom-map.mjs
 *
 * The outline is the country as Natural Earth records it. No neighbouring
 * countries are drawn or labelled, no disputed boundaries are asserted, and
 * cities appear as plain dots with no invented data attached (brief §3).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const SA_NUMERIC = "682";
const WIDTH = 1000;
const HEIGHT = 720;
const PADDING = 24;
/** Ramer–Douglas–Peucker tolerance, in projected units. */
const TOLERANCE = 0.8;

const topology = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topology, topology.objects.countries);
const saudi = countries.features.find((f) => f.id === SA_NUMERIC);
if (!saudi) throw new Error("Saudi Arabia (682) not found in the topology");

/** Every ring in the geometry, as [lon, lat] pairs. */
const rings = saudi.geometry.type === "Polygon" ? saudi.geometry.coordinates : saudi.geometry.coordinates.flat();

// An equirectangular projection, corrected for latitude so the country is not
// stretched sideways. At ~24°N that matters: cos(24°) is about 0.91.
const all = rings.flat();
const lons = all.map((c) => c[0]);
const lats = all.map((c) => c[1]);
const midLat = (Math.min(...lats) + Math.max(...lats)) / 2;
const k = Math.cos((midLat * Math.PI) / 180);

const rawProject = ([lon, lat]) => [lon * k, -lat];
const projected = rings.map((ring) => ring.map(rawProject));

const xs = projected.flat().map((p) => p[0]);
const ys = projected.flat().map((p) => p[1]);
const minX = Math.min(...xs);
const maxX = Math.max(...xs);
const minY = Math.min(...ys);
const maxY = Math.max(...ys);

const scale = Math.min((WIDTH - PADDING * 2) / (maxX - minX), (HEIGHT - PADDING * 2) / (maxY - minY));
const offsetX = (WIDTH - (maxX - minX) * scale) / 2;
const offsetY = (HEIGHT - (maxY - minY) * scale) / 2;

const toCanvas = ([x, y]) => [(x - minX) * scale + offsetX, (y - minY) * scale + offsetY];

/** Projects a geographic point into the same canvas, for city markers. */
const place = (lon, lat) => toCanvas(rawProject([lon, lat]));

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const sqTolerance = tolerance * tolerance;

  const sqSegDist = (p, a, b) => {
    let [x, y] = a;
    let dx = b[0] - x;
    let dy = b[1] - y;
    if (dx !== 0 || dy !== 0) {
      const t = ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy);
      if (t > 1) [x, y] = b;
      else if (t > 0) [x, y] = [x + dx * t, y + dy * t];
    }
    dx = p[0] - x;
    dy = p[1] - y;
    return dx * dx + dy * dy;
  };

  const keep = new Array(points.length).fill(false);
  keep[0] = keep[points.length - 1] = true;
  const stack = [[0, points.length - 1]];

  while (stack.length) {
    const [first, last] = stack.pop();
    let index = -1;
    let maxDist = sqTolerance;
    for (let i = first + 1; i < last; i++) {
      const dist = sqSegDist(points[i], points[first], points[last]);
      if (dist > maxDist) {
        index = i;
        maxDist = dist;
      }
    }
    if (index > -1) {
      keep[index] = true;
      stack.push([first, index], [index, last]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const round = (n) => Math.round(n * 10) / 10;

const paths = projected
  .map((ring) => simplify(ring.map(toCanvas), TOLERANCE))
  // Drop slivers left by simplification; keep the mainland and real islands.
  .filter((ring) => ring.length > 8)
  .map((ring) => `M${ring.map(([x, y]) => `${round(x)},${round(y)}`).join("L")}Z`);

const cities = {
  madinah: place(39.61, 24.47),
  jeddah: place(39.19, 21.49),
  riyadh: place(46.72, 24.71),
};

const out = `// GENERATED by scripts/build-kingdom-map.mjs — do not edit by hand.
//
// Outline of Saudi Arabia, derived from Natural Earth 1:50m Admin 0 Countries,
// which is in the public domain. Simplified for display; not for navigation.
// Credit is shown on the page beside the map.
//
// No neighbouring countries are drawn or labelled, and no boundary here should
// be read as asserting a position on any disputed border.
export const KINGDOM_VIEWBOX = "0 0 ${WIDTH} ${HEIGHT}";

export const KINGDOM_PATHS: readonly string[] = ${JSON.stringify(paths, null, 2)};

/** Projected city positions, matching the viewBox above. */
export const KINGDOM_CITIES: Record<string, { x: number; y: number }> = {
${Object.entries(cities)
  .map(([name, [x, y]]) => `  ${name}: { x: ${round(x)}, y: ${round(y)} },`)
  .join("\n")}
};

export const KINGDOM_SOURCE = {
  name: "Natural Earth",
  detail: "1:50m Admin 0 Countries, public domain",
  url: "https://www.naturalearthdata.com/",
};
`;

writeFileSync("src/content/kingdom-map.ts", out, "utf8");

const bytes = Buffer.byteLength(out);
console.log(`wrote src/content/kingdom-map.ts`);
console.log(`  rings kept: ${paths.length}`);
console.log(`  points: ${projected.reduce((n, r) => n + r.length, 0)} -> ${paths.reduce((n, p) => n + p.split("L").length, 0)}`);
console.log(`  size: ${(bytes / 1024).toFixed(1)} KB`);
